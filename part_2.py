# === Load your trained model (already done)
model.eval()

# === Grad-CAM Hook
gradients = None
activations = None

def save_gradients_hook(module, grad_input, grad_output):
    global gradients
    gradients = grad_output[0]

def save_activation_hook(module, input, output):
    global activations
    activations = output

# Register hooks on last conv layer
target_layer = model.layer4[1].conv2
target_layer.register_forward_hook(save_activation_hook)
target_layer.register_backward_hook(save_gradients_hook)

# === Load one image
img_path = "/content/drive/MyDrive/antibiotic_p/data/cell_patches/Control/cell_00001.png"
img_pil = Image.open(img_path).convert("RGB")
transform = transforms.Compose([
    transforms.Resize((64, 64)),
    transforms.ToTensor(),
])
img_tensor = transform(img_pil).unsqueeze(0).to(device)

# === Forward + Backward pass
output = model(img_tensor)
pred_class = output.argmax(dim=1).item()

model.zero_grad()
class_score = output[0, pred_class]
class_score.backward()

# === Grad-CAM calculation
weights = gradients.mean(dim=(2, 3), keepdim=True)  # Global average pooling
cam = (weights * activations).sum(dim=1).squeeze().detach().cpu().numpy()

cam = np.maximum(cam, 0)
cam = cv2.resize(cam, (64, 64))
cam = (cam - cam.min()) / (cam.max() - cam.min())

# === Overlay CAM
heatmap = cv2.applyColorMap(np.uint8(255 * cam), cv2.COLORMAP_JET)
img_np = np.array(img_pil.resize((64, 64)))
overlay = cv2.addWeighted(img_np, 0.5, heatmap, 0.5, 0)

