import os
import numpy as np
import tifffile as tiff
import matplotlib.pyplot as plt
import pandas as pd
from sklearn.metrics import f1_score, jaccard_score, precision_score, recall_score, accuracy_score, confusion_matrix
from skimage import measure

# === Folder setup ===
gt_folder = "/content/drive/MyDrive/antibiotic_p/Ground Truth/"
pred_folder = "/content/drive/MyDrive/antibiotic_p/segmentation_mask/"
output_folder = os.path.join(pred_folder, "outputs/")
os.makedirs(output_folder, exist_ok=True)

# === Get .tif ground truth file list ===
file_names = sorted([f for f in os.listdir(gt_folder) if f.endswith('.tif')])

# === Results storage ===
results = []

# === Settings ===
min_object_size = 30  # Ignore tiny blobs (false positives)

for fname in file_names:
    name = os.path.splitext(fname)[0]  # e.g., "#2_translated_Chloramphenicol_1"
    gt_path = os.path.join(gt_folder, fname)
    pred_path = os.path.join(pred_folder, name + "_masks.npy")  # ✅ fixed suffix

    # ✅ Debug: Check paths
    print(f"Processing: {name}")
    print(f"GT:   {gt_path}")
    print(f"PRED: {pred_path}")

    if not os.path.exists(pred_path):
        print(f"❌ Prediction file not found for {name}, skipping.\n")
        continue

    # === Load ground truth
    gt = tiff.imread(gt_path) > 0

    # === Load Cellpose prediction
    pred_data = np.load(pred_path, allow_pickle=True).item()
    pred_mask = pred_data['masks'] > 0

    # === Remove small predicted blobs
    labeled_pred = measure.label(pred_mask)
    cleaned_pred = np.zeros_like(pred_mask)

    for region in measure.regionprops(labeled_pred):
        if region.area >= min_object_size:
            cleaned_pred[labeled_pred == region.label] = 1

    pred = cleaned_pred.astype(bool)

    # === Compute metrics
    gt_flat = gt.flatten()
    pred_flat = pred.flatten()

    f1 = f1_score(gt_flat, pred_flat)
    iou = jaccard_score(gt_flat, pred_flat)
    precision = precision_score(gt_flat, pred_flat)
    recall = recall_score(gt_flat, pred_flat)
    accuracy = accuracy_score(gt_flat, pred_flat)

    tn, fp, fn, tp = confusion_matrix(gt_flat, pred_flat).ravel()

    results.append([name, f1, iou, precision, recall, accuracy, tp, fp, fn, tn])

    # === Create overlay (TP=G, FP=R, FN=B)
    tp_mask = np.logical_and(gt == 1, pred == 1)
    fp_mask = np.logical_and(gt == 0, pred == 1)
    fn_mask = np.logical_and(gt == 1, pred == 0)
    overlay = np.stack([fp_mask, tp_mask, fn_mask], axis=-1).astype(np.uint8) * 255

    plt.figure(figsize=(5, 5))
    plt.imshow(overlay)
    plt.title(f"{name}\nTP=G | FP=R | FN=B\nF1={f1:.2f} | IoU={iou:.2f}")
    plt.axis("off")
    plt.tight_layout()
    plt.savefig(os.path.join(output_folder, f"{name}_overlay.png"))
    plt.close()

# === Save all metrics
columns = ["Image", "F1", "IoU", "Precision", "Recall", "Accuracy", "TP", "FP", "FN", "TN"]
df = pd.DataFrame(results, columns=columns)
df.to_csv(os.path.join(output_folder, "metrics_summary.csv"), index=False)

# === Print summary
print("\n=== Mean Metrics ===")
print(df.iloc[:, 1:6].mean().round(4))

print("\n=== Standard Deviation ===")
print(df.iloc[:, 1:6].std().round(4))

import os
import numpy as np
import tifffile as tiff
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
from sklearn.metrics import f1_score, jaccard_score, precision_score, recall_score, accuracy_score, confusion_matrix
from skimage import measure

# === Your folders ===
gt_folder = "/content/drive/MyDrive/antibiotic_p/Ground Truth/"
pred_folder = "/content/drive/MyDrive/antibiotic_p/segmentation_mask/"
output_folder = os.path.join(pred_folder, "outputs/")
os.makedirs(output_folder, exist_ok=True)

# === Collect filenames from GT folder
file_names = sorted([f for f in os.listdir(gt_folder) if f.endswith(".tif")])

# === Metrics storage
results = []

# === Settings
min_object_size = 30  # remove small blobs

for fname in file_names:
    name = os.path.splitext(fname)[0]
    gt_path = os.path.join(gt_folder, fname)
    pred_path = os.path.join(pred_folder, name + "_masks.npy")

    if not os.path.exists(pred_path):
        print(f"Skipping {name}: prediction file not found.")
        continue

    print(f"Processing: {name}")

    # Load ground truth
    gt = tiff.imread(gt_path) > 0

    # Load prediction
    pred_data = np.load(pred_path, allow_pickle=True).item()
    pred_mask = pred_data['masks'] > 0

    # Remove small blobs
    labeled = measure.label(pred_mask)
    cleaned = np.zeros_like(pred_mask)
    for region in measure.regionprops(labeled):
        if region.area >= min_object_size:
            cleaned[labeled == region.label] = 1
    pred = cleaned.astype(bool)

    # Flatten
    gt_flat = gt.flatten()
    pred_flat = pred.flatten()

    # Metrics
    f1 = f1_score(gt_flat, pred_flat)
    iou = jaccard_score(gt_flat, pred_flat)
    precision = precision_score(gt_flat, pred_flat)
    recall = recall_score(gt_flat, pred_flat)
    accuracy = accuracy_score(gt_flat, pred_flat)
    tn, fp, fn, tp = confusion_matrix(gt_flat, pred_flat).ravel()

    # Store results
    results.append([name, f1, iou, precision, recall, accuracy, tp, fp, fn, tn])

    # Overlay map (TP=green, FP=red, FN=blue)
    tp_mask = np.logical_and(gt == 1, pred == 1)
    fp_mask = np.logical_and(gt == 0, pred == 1)
    fn_mask = np.logical_and(gt == 1, pred == 0)
    overlay = np.stack([fp_mask, tp_mask, fn_mask], axis=-1).astype(np.uint8) * 255

    # Save overlay
    plt.figure(figsize=(5, 5))
    plt.imshow(overlay)
    plt.title(f"{name}\nTP=G | FP=R | FN=B\nF1={f1:.2f}, IoU={iou:.2f}")
    plt.axis("off")
    plt.tight_layout()
    plt.savefig(os.path.join(output_folder, f"{name}_overlay.png"))
    plt.close()

    # Save per-image confusion matrix
    plt.figure(figsize=(4, 3))
    sns.heatmap([[tn, fp], [fn, tp]], annot=True, fmt='d', cmap='Oranges',
                xticklabels=['Pred: 0', 'Pred: 1'],
                yticklabels=['True: 0', 'True: 1'])
    plt.title(f"Confusion Matrix: {name}")
    plt.tight_layout()
    plt.savefig(os.path.join(output_folder, f"{name}_confusion.png"))
    plt.close()

# === Save results to CSV
columns = ["Image", "F1", "IoU", "Precision", "Recall", "Accuracy", "TP", "FP", "FN", "TN"]
df = pd.DataFrame(results, columns=columns)
df.to_csv(os.path.join(output_folder, "metrics_summary.csv"), index=False)

# === Print summary
print("\n=== Mean Metrics ===")
print(df.iloc[:, 1:6].mean().round(4))

print("\n=== Standard Deviation ===")
print(df.iloc[:, 1:6].std().round(4))

