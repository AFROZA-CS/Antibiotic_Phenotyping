import os
import numpy as np
import matplotlib.pyplot as plt
from PIL import Image
from skimage.filters import threshold_otsu
from skimage.morphology import binary_opening, remove_small_objects, disk
from skimage.color import label2rgb
from sklearn.metrics import jaccard_score, f1_score

# 📁 Update your base path
base_path = "/content/drive/MyDrive/qxz/Antibiotic Phenotyping/DeepBacs_Data_Object_Detection_E.coli_Antibiotic_Phenotyping/Bacterial_Nucleoid_Study"
antibiotics = ["Antibiotic_A", "Antibiotic_B", "Antibiotic_C", "Antibiotic_D", "Antibiotic_E"]

# 🔬 Segment DAPI
def segment_dapi(image_rgb):
    dapi = image_rgb[..., 2]
    thresh = threshold_otsu(dapi)
    mask = dapi > thresh
    mask = binary_opening(mask, disk(1))
    mask = remove_small_objects(mask, min_size=20)
    return dapi, mask

# 📏 Compute accuracy
def compute_accuracy(auto_mask, manual_mask):
    auto_flat = auto_mask.flatten().astype(bool)
    manual_flat = manual_mask.flatten().astype(bool)
    iou = jaccard_score(manual_flat, auto_flat)
    dice = f1_score(manual_flat, auto_flat)
    return iou, dice

for ab in antibiotics:
    ab_path = os.path.join(base_path, ab)
    image_files = sorted([
        f for f in os.listdir(ab_path)
        if f.lower().endswith(('.png', '.jpg', '.tif')) and '_manual_mask' not in f
    ])

    if not image_files:
        continue

    print(f"\n🔬 Processing: {ab}")
    img_file = image_files[0]  # first image for each antibiotic
    img_path = os.path.join(ab_path, img_file)
    image = np.array(Image.open(img_path).convert('RGB'))

    # Segment DAPI
    dapi, auto_mask = segment_dapi(image)

    # Try to load manual mask (optional)
    manual_mask_file = img_file.replace('.', '_manual_mask.')
    manual_mask_path = os.path.join(ab_path, manual_mask_file)
    manual_mask = None
    if os.path.exists(manual_mask_path):
        manual_mask = np.array(Image.open(manual_mask_path).convert('L')) > 0
        iou, dice = compute_accuracy(auto_mask, manual_mask)
        acc_text = f"IoU: {iou:.2f}, Dice: {dice:.2f}"
    else:
        acc_text = "Manual mask not found"

    # Overlay auto mask on image
    overlay = label2rgb(auto_mask, image=image, bg_label=0)

    # Plot
    fig, axs = plt.subplots(1, 4, figsize=(20, 5))
    axs[0].imshow(image)
    axs[0].set_title("Original")
    axs[1].imshow(dapi, cmap='gray')
    axs[1].set_title("DAPI Channel")
    axs[2].imshow(manual_mask if manual_mask is not None else np.zeros_like(auto_mask), cmap='gray')
    axs[2].set_title("Manual Mask" if manual_mask is not None else "Manual Mask (missing)")
    axs[3].imshow(overlay)
    axs[3].set_title(f"Auto Mask Overlay\n{acc_text}")

    for ax in axs:
        ax.axis('off')

    plt.suptitle(f"{ab} - {img_file}", fontsize=14)
    plt.tight_layout()
    plt.show()