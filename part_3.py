# === Storage
data = []

# === Loop over classes
for class_name in sorted(os.listdir(patch_folder)):
    class_dir = os.path.join(patch_folder, class_name)
    if not os.path.isdir(class_dir): continue

    for fname in tqdm(os.listdir(class_dir), desc=f"Processing {class_name}"):
        if not fname.endswith(".png"): continue
        fpath = os.path.join(class_dir, fname)
        img = io.imread(fpath)

        red = img[:, :, 0]  # Membrane
        blue = img[:, :, 2]  # DNA

        # Threshold & label membrane
        mem_thresh = threshold_otsu(red)
        mem_mask = closing(red > mem_thresh, disk(1))
        mem_props = regionprops(label(mem_mask))

        # Threshold & label DNA
        dna_thresh = threshold_otsu(blue)
        dna_mask = closing(blue > dna_thresh, disk(1))
        dna_props = regionprops(label(dna_mask))

        # If no objects, skip
        if not mem_props or not dna_props:
            continue

        mem = mem_props[0]
        dna = dna_props[0]

        entry = {
            "Class": class_name,
            "Image": fname,

            # Intensity
            "Membrane_Intensity": red[mem_mask].mean(),
            "DNA_Intensity": blue[dna_mask].mean(),

            # Area
            "Membrane_Area": mem.area,
            "DNA_Area": dna.area,

            # Shape
            "Membrane_Circularity": (4 * np.pi * mem.area) / (mem.perimeter ** 2 + 1e-5),
            "DNA_Circularity": (4 * np.pi * dna.area) / (dna.perimeter ** 2 + 1e-5),

            # Ratio
            "DNA_to_Membrane_Intensity": blue[dna_mask].mean() / (red[mem_mask].mean() + 1e-5),
            "DNA_to_Membrane_Area": dna.area / (mem.area + 1e-5),
        }

        data.append(entry)

# === Save to CSV
