"""Part A: Bounding Box Annotations (from XML)

Step 1: Define image pairs and paths
"""

import os
import xml.etree.ElementTree as ET
import pandas as pd

# Paths
annotation_dir = '/content/drive/MyDrive/qxz/Antibiotic Phenotyping/DeepBacs_Data_Object_Detection_E.coli_Antibiotic_Phenotyping/train/annotations'

# Image pairs: Control and Chloramphenicol
image_pairs = [
    ('#2_translated_control_1', '#2_translated_Chloramphenicol_1'),
    ('#2_translated_control_2', '#2_translated_Chloramphenicol_2'),
    ('#2_translated_control_3', '#2_translated_Chloramphenicol_3'),
    ('#2_translated_control_4', '#2_translated_Chloramphenicol_4'),
]

"""Step 2: Extract bounding box morphology"""

bbox_data = []

for pair_id, (control_id, cam_id) in enumerate(image_pairs, start=1):
    for image_id, treatment in [(control_id, 'Control'), (cam_id, 'CAM')]:
        xml_path = os.path.join(annotation_dir, image_id + '.xml')
        tree = ET.parse(xml_path)
        root = tree.getroot()

        for obj in root.findall('object'):
            label = obj.find('name').text
            if label not in ['Control', 'Oblique', 'Vesicle']:
                continue

            bndbox = obj.find('bndbox')
            xmin = int(float(bndbox.find('xmin').text))
            ymin = int(float(bndbox.find('ymin').text))
            xmax = int(float(bndbox.find('xmax').text))
            ymax = int(float(bndbox.find('ymax').text))

            width = xmax - xmin
            height = ymax - ymin
            area = width * height
            aspect_ratio = width / height if height else 0

            bbox_data.append({
                'image_id': image_id,
                'pair_id': pair_id,
                'treatment': treatment,
                'label': label,
                'area': area,
                'aspect_ratio': aspect_ratio,
                'source': 'bounding_box',
                'eccentricity': None  # not applicable
            })

df_bbox = pd.DataFrame(bbox_data)
print("✅ Bounding box morphology extracted.")
df_bbox.head()

"""Step 3: Visualize bounding box morphology"""

import seaborn as sns
import matplotlib.pyplot as plt

for feat in ['area', 'aspect_ratio']:
    plt.figure(figsize=(10, 5))
    sns.boxplot(data=df_bbox, x='pair_id', y=feat, hue='treatment')
    sns.stripplot(data=df_bbox, x='pair_id', y=feat, hue='treatment',
                  dodge=True, color='black', alpha=0.3, jitter=0.3)
    plt.title(f"{feat.title()} (Bounding Box)")
    plt.xlabel("Pair ID")
    plt.grid(True)
    plt.legend().set_title("Treatment")
    plt.show()

"""Part B: Segmentation Masks (Cellpose .npy)

Step 1: Define mask path and image pairs
"""

import numpy as np
from skimage.measure import regionprops, label

mask_dir = '/content/drive/MyDrive/qxz/Antibiotic Phenotyping/DeepBacs_Data_Object_Detection_E.coli_Antibiotic_Phenotyping/train/cellpose_output'

image_pairs = [
    ('#2_translated_control_1', '#2_translated_Chloramphenicol_1'),
    ('#2_translated_control_2', '#2_translated_Chloramphenicol_2'),
    ('#2_translated_control_3', '#2_translated_Chloramphenicol_3'),
    ('#2_translated_control_4', '#2_translated_Chloramphenicol_4'),
]

"""Step 2: Extract segmentation-based morphology"""

mask_data = []

for pair_id, (control_id, cam_id) in enumerate(image_pairs, start=1):
    for image_id, treatment in [(control_id, 'Control'), (cam_id, 'CAM')]:
        mask_path = os.path.join(mask_dir, image_id + '_masks.npy')
        mask_dict = np.load(mask_path, allow_pickle=True).item()
        masks = mask_dict['masks']
        props = regionprops(label(masks))

        for region in props:
            area = region.area
            major = region.major_axis_length
            minor = region.minor_axis_length
            aspect_ratio = major / minor if minor else 0
            eccentricity = region.eccentricity

            mask_data.append({
                'image_id': image_id,
                'pair_id': pair_id,
                'treatment': treatment,
                'label': treatment,
                'area': area,
                'aspect_ratio': aspect_ratio,
                'eccentricity': eccentricity,
                'source': 'segmentation'
            })

df_mask = pd.DataFrame(mask_data)
print("✅ Segmentation morphology extracted.")
df_mask.head()

"""Step 3: Visualize segmentation morphology"""

for feat in ['area', 'aspect_ratio', 'eccentricity']:
    plt.figure(figsize=(10, 5))
    sns.boxplot(data=df_mask, x='pair_id', y=feat, hue='treatment')
    sns.stripplot(data=df_mask, x='pair_id', y=feat, hue='treatment',
                  dodge=True, color='black', alpha=0.3, jitter=0.3)
    plt.title(f"{feat.title()} (Segmentation)")
    plt.xlabel("Pair ID")
    plt.grid(True)
    plt.legend().set_title("Treatment")
    plt.show()

df_combined = pd.concat([df_bbox, df_mask], ignore_index=True)