import os
import numpy as np
from PIL import Image
from skimage.measure import regionprops, label
import matplotlib.pyplot as plt
from tqdm import tqdm

# === CONFIG ===
image_root = "/content/drive/MyDrive/antibiotic_p/data/Image"
mask_root = "/content/drive/MyDrive/antibiotic_p/data/Mask"
output_root = "//content/drive/MyDrive/antibiotic_p/data/cell_patches"
resize_size = (64, 64)
min_cell_area = 30

# === Create output directory
os.makedirs(output_root, exist_ok=True)

# === Loop through each condition ===
for class_name in os.listdir(image_root):
    image_folder = os.path.join(image_root, class_name)
    mask_folder = os.path.join(mask_root, class_name)

    if not os.path.isdir(image_folder) or class_name.startswith("."):
        continue

    save_folder = os.path.join(output_root, class_name)
    os.makedirs(save_folder, exist_ok=True)

    image_files = [f for f in os.listdir(image_folder)
                   if f.endswith(".png") and not f.startswith(".")]

    patch_index = 0
    preview_patches = []

    for fname in tqdm(image_files, desc=f"Processing {class_name}"):
        base = os.path.splitext(fname)[0]
        img_path = os.path.join(image_folder, fname)
        mask_path = os.path.join(mask_folder, base + "_masks.npy")

        if not os.path.exists(mask_path):
            print(f"❌ Mask not found for {fname}")
            continue

        # Load image and mask
        image = np.array(Image.open(img_path))
        try:
            pred_data = np.load(mask_path, allow_pickle=True).item()
            mask = pred_data["masks"]
        except Exception as e:
            print(f"❌ Failed to load mask for {fname}: {e}")
            continue

        labeled = label(mask)

        for region in regionprops(labeled):
            if region.area < min_cell_area:
                continue

            minr, minc, maxr, maxc = region.bbox
            crop_rgb = image[minr:maxr, minc:maxc]
            crop_mask = (labeled[minr:maxr, minc:maxc] == region.label).astype(np.uint8)
            masked = crop_rgb * np.expand_dims(crop_mask, axis=-1)

            # Pad to square
            h, w = masked.shape[:2]
            pad_r = (max(w - h, 0) // 2, max(w - h, 0) - max(w - h, 0) // 2)
            pad_c = (max(h - w, 0) // 2, max(h - w, 0) - max(h - w, 0) // 2)
            padded = np.pad(masked, (pad_r, pad_c, (0, 0)), mode='constant')

            patch = Image.fromarray(padded).resize(resize_size)
            patch_path = os.path.join(save_folder, f"cell_{patch_index:05d}.png")
            patch.save(patch_path)
            patch_index += 1

            if patch_index <= 5:
                preview_patches.append(np.array(patch))

    # === Preview a few patches from this class
    if preview_patches:
        print(f"🔍 Sample patches from {class_name}")
        fig, axs = plt.subplots(1, len(preview_patches), figsize=(len(preview_patches) * 2, 2))
        for i, patch in enumerate(preview_patches):
            axs[i].imshow(patch)
            axs[i].axis('off')
            axs[i].set_title(f"Cell {i+1}")
        plt.tight_layout()
        plt.show()

