import torch
import torch.nn as nn
import numpy as np
from torchvision import datasets, transforms, models
from torchvision.models.swin_transformer import swin_t
from torch.utils.data import DataLoader, Subset
import timm
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import classification_report, confusion_matrix
import matplotlib.pyplot as plt
import seaborn as sns
from scipy.stats import mode

device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

data_path = "/content/drive/MyDrive/antibiotic_p/data/cell_patches"
test_idx_path = "/content/drive/MyDrive/antibiotic_p/test_idx.npy"

transform = transforms.Compose([
    transforms.Resize((224, 224)),
    transforms.ToTensor(),
    transforms.Normalize([0.5]*3, [0.5]*3)
])

dataset = datasets.ImageFolder(root=data_path, transform=transform)
class_names = dataset.classes
num_classes = len(class_names)

test_idx = np.load(test_idx_path)
test_dataset = Subset(dataset, test_idx)
test_loader = DataLoader(test_dataset, batch_size=32, shuffle=False)

# === Device setup ===
device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

# === Swin Transformer ===
model_swin = swin_t(weights=None)
model_swin.head = nn.Linear(model_swin.head.in_features, num_classes)
model_swin.load_state_dict(torch.load("/content/drive/MyDrive/antibiotic_p/model_swin_FIXED_v2.pth"))
model_swin = model_swin.to(device).eval()

# === CoaT ===
model_coat = timm.create_model("coat_tiny", pretrained=False, num_classes=num_classes)
model_coat.load_state_dict(torch.load("/content/drive/MyDrive/antibiotic_p/model_coat_FIXED.pth"))
model_coat = model_coat.to(device).eval()

# === ResNet18 ===
model_resnet = models.resnet18(weights="IMAGENET1K_V1")
model_resnet.fc = nn.Linear(model_resnet.fc.in_features, num_classes)
model_resnet.load_state_dict(torch.load("/content/drive/MyDrive/antibiotic_p/model_part2_FIXED_v2.pth"))
model_resnet = model_resnet.to(device).eval()

def get_probs(model, dataloader, device):
    model.eval()
    all_probs, all_labels = [], []

    with torch.no_grad():
        for x, y in dataloader:
            x = x.to(device)
            out = model(x)
            prob = torch.softmax(out, dim=1)
            all_probs.append(prob.cpu())
            all_labels.append(y)

    return torch.cat(all_probs).numpy(), torch.cat(all_labels).numpy()

probs_swin, y_true = get_probs(model_swin, test_loader, device)
probs_coat, _ = get_probs(model_coat, test_loader, device)
probs_resnet, _ = get_probs(model_resnet, test_loader, device)

pred_swin = np.argmax(probs_swin, axis=1)
pred_coat = np.argmax(probs_coat, axis=1)
pred_resnet = np.argmax(probs_resnet, axis=1)

all_preds = np.vstack([pred_swin, pred_coat, pred_resnet])
hard_vote = mode(all_preds, axis=0).mode.squeeze()

print("Hard Voting:")
print(classification_report(y_true, hard_vote, target_names=class_names))

cm = confusion_matrix(y_true, hard_vote)
sns.heatmap(cm, annot=True, fmt="d", cmap="Blues", xticklabels=class_names, yticklabels=class_names)
plt.title("Hard Voting Confusion Matrix")
plt.show()

avg_probs = (probs_swin + probs_coat + probs_resnet) / 3
soft_vote = np.argmax(avg_probs, axis=1)

print(" Soft Voting:")
print(classification_report(y_true, soft_vote, target_names=class_names))

cm = confusion_matrix(y_true, soft_vote)
sns.heatmap(cm, annot=True, fmt="d", cmap="Blues", xticklabels=class_names, yticklabels=class_names)
plt.title("Soft Voting Confusion Matrix")
plt.show()

weighted_probs = (
    0.4 * probs_swin +
    0.3 * probs_coat +
    0.3 * probs_resnet
)
weighted_vote = np.argmax(weighted_probs, axis=1)

print("Weighted Soft Voting:")
print(classification_report(y_true, weighted_vote, target_names=class_names))

cm = confusion_matrix(y_true, weighted_vote)
sns.heatmap(cm, annot=True, fmt="d", cmap="Blues", xticklabels=class_names, yticklabels=class_names)
plt.title("Weighted Voting Confusion Matrix")
plt.show()

X_stack = np.hstack((probs_swin, probs_coat, probs_resnet))
meta_model = LogisticRegression(max_iter=1000)
meta_model.fit(X_stack, y_true)
stack_preds = meta_model.predict(X_stack)

print(" Stacking Ensemble:")
print(classification_report(y_true, stack_preds, target_names=class_names))

cm = confusion_matrix(y_true, stack_preds)
sns.heatmap(cm, annot=True, fmt="d", cmap="Blues", xticklabels=class_names, yticklabels=class_names)
plt.title("Stacking Confusion Matrix")
plt.show()
