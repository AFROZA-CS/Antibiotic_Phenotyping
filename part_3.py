for class_name in classes:
    class_path = os.path.join(patch_folder, class_name)
    image_files = sorted([f for f in os.listdir(class_path) if f.endswith(".png")])
    selected = random.sample(image_files, min(num_samples, len(image_files)))

    for fname in selected:
        img_path = os.path.join(class_path, fname)
        img_pil = Image.open(img_path).convert("RGB")
        img_tensor = transform(img_pil).unsqueeze(0).to(device)

        activations.clear()
        gradients.clear()

        # Forward
        output = model(img_tensor)
        pred_class = output.argmax(dim=1).item()

        # Backward
        one_hot = torch.zeros_like(output)
        one_hot[0, pred_class] = 1
        output.backward(gradient=one_hot)

        # Grad-CAM
        act = activations[0].squeeze().detach().cpu().numpy()
        grad = gradients[0].squeeze().detach().cpu().numpy()
        weights = grad.mean(axis=(1, 2))
        cam = np.zeros(act.shape[1:], dtype=np.float32)
        for i, w in enumerate(weights):
            cam += w * act[i]
        cam = np.maximum(cam, 0)
        cam = cv2.resize(cam, (64, 64))
        cam -= cam.min()
        cam /= cam.max()
        cam = np.uint8(255 * cam)

        # Overlay
        img_np = np.array(img_pil.resize((64, 64)))
        heatmap = cv2.applyColorMap(cam, cv2.COLORMAP_JET)
        overlay = cv2.addWeighted(img_np, 0.5, heatmap, 0.5, 0)

