import torch
import torch.nn as nn
import torch.optim as optim
from torchvision import models
from tqdm import tqdm
import matplotlib.pyplot as plt

# === Model Setup
device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
model = models.resnet18(pretrained=True)
model.fc = nn.Linear(model.fc.in_features, len(class_names))  # Adjust final layer
model = model.to(device)

# === Loss & Optimizer
criterion = nn.CrossEntropyLoss()
optimizer = optim.Adam(model.parameters(), lr=1e-4)

# === Training Loop
def train_model(model, train_loader, test_loader, epochs=10):
    train_acc, test_acc, train_loss_vals = [], [], []

    for epoch in range(epochs):
        model.train()
        total_loss, correct, total = 0, 0, 0

        for images, labels in tqdm(train_loader, desc=f"Epoch {epoch+1}/{epochs}"):
            images, labels = images.to(device), labels.to(device)

            optimizer.zero_grad()
            outputs = model(images)
            loss = criterion(outputs, labels)
            loss.backward()
            optimizer.step()

            total_loss += loss.item()
            _, predicted = outputs.max(1)
            correct += (predicted == labels).sum().item()
            total += labels.size(0)

        acc = correct / total
        train_acc.append(acc)
        train_loss_vals.append(total_loss / len(train_loader))

        # === Evaluate
        model.eval()
        correct, total = 0, 0
        with torch.no_grad():
            for images, labels in test_loader:
                images, labels = images.to(device), labels.to(device)
                outputs = model(images)
                _, predicted = outputs.max(1)
                correct += (predicted == labels).sum().item()
                total += labels.size(0)

        test_acc.append(correct / total)
        print(f"✅ Epoch {epoch+1} | Train Acc: {acc:.4f} | Test Acc: {test_acc[-1]:.4f} | Loss: {train_loss_vals[-1]:.4f}")

    return train_loss_vals, train_acc, test_acc

# === Run Training
loss_vals, train_acc, test_acc = train_model(model, train_loader, test_loader, epochs=10)

# === Plot Results
plt.figure(figsize=(10,4))
