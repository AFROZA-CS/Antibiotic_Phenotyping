import os
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
from PIL import Image
from skimage.filters import threshold_otsu
from skimage.measure import label, regionprops_table
from skimage.morphology import binary_opening, remove_small_objects, disk

# Path to your main study folder in Google Drive
BASE_PATH = "/content/drive/MyDrive/qxz/Antibiotic Phenotyping/DeepBacs_Data_Object_Detection_E.coli_Antibiotic_Phenotyping/Bacterial_Nucleoid_Study"

# List your antibiotic folders
antibiotics = ["Antibiotic_A", "Antibiotic_B", "Antibiotic_C", "Antibiotic_D", "Antibiotic_E"]

results = []

for ab in antibiotics:
    folder_path = os.path.join(BASE_PATH, ab)
    for filename in os.listdir(folder_path):
        if not filename.endswith(".png") and not filename.endswith(".tif"):
            continue

        # Load image
        img_path = os.path.join(folder_path, filename)
        image = np.array(Image.open(img_path).convert('RGB'))

        # Extract DAPI (blue channel)
        dapi = image[..., 2]

        # Threshold and clean
        thresh = threshold_otsu(dapi)
        mask = dapi > thresh
        mask = binary_opening(mask, disk(1))
        mask = remove_small_objects(mask, min_size=20)

        # Label and extract shape features
        label_img = label(mask)
        props = regionprops_table(label_img, properties=[
            'label', 'area', 'perimeter', 'eccentricity', 'solidity',
            'major_axis_length', 'minor_axis_length'
        ])
        df_props = pd.DataFrame(props)
        df_props['Antibiotic'] = ab
        df_props['Image'] = filename
        results.append(df_props)

# Combine all results into one DataFrame
full_df = pd.concat(results, ignore_index=True)

# Save to Drive
output_csv = os.path.join(BASE_PATH, "nucleoid_shape_data.csv")
