# === Imports ===
import os
import torch
import torch.nn as nn
import torch.optim as optim
import numpy as np
from torchvision import datasets, transforms
from torchvision.models import convnext_tiny, ConvNeXt_Tiny_Weights
from torch.utils.data import DataLoader, Subset
from sklearn.model_selection import train_test_split
from sklearn.metrics import confusion_matrix, classification_report
import matplotlib.pyplot as plt
import seaborn as sns

# === Paths ===
data_path = "/content/drive/MyDrive/antibiotic_p/data/cell_patches"
model_save_path = "/content/drive/MyDrive/antibiotic_p/model_convnext_FIXED.pth"
split_file = "/content/drive/MyDrive/antibiotic_p/test_idx.npy"
batch_size = 32
num_epochs = 10

# === Device ===
device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

# === Transforms ===
transform = transforms.Compose([
    transforms.Resize((224, 224)),
    transforms.ToTensor(),
    transforms.Normalize([0.5]*3, [0.5]*3)
])

# === Load full dataset ===
dataset = datasets.ImageFolder(root=data_path, transform=transform)
class_names = dataset.classes
num_classes = len(class_names)

# === Consistent train/test split ===
if os.path.exists(split_file):
    test_idx = np.load(split_file)
    train_idx = [i for i in range(len(dataset)) if i not in test_idx]
else:
    labels = [sample[1] for sample in dataset.samples]
    train_idx, test_idx = train_test_split(
        np.arange(len(dataset)),
        test_size=0.2,
        stratify=labels,
        random_state=42
    )
    np.save(split_file, test_idx)

train_dataset = Subset(dataset, train_idx)
test_dataset = Subset(dataset, test_idx)

train_loader = DataLoader(train_dataset, batch_size=batch_size, shuffle=True)
test_loader = DataLoader(test_dataset, batch_size=batch_size, shuffle=False)

# === Load ConvNeXt (with ImageNet weights) ===
weights = ConvNeXt_Tiny_Weights.DEFAULT
model = convnext_tiny(weights=weights)
model.classifier[2] = nn.Linear(model.classifier[2].in_features, num_classes)
model = model.to(device)

# === Loss & Optimizer ===
criterion = nn.CrossEntropyLoss()
optimizer = optim.AdamW(model.parameters(), lr=1e-4)

# === Training Loop ===
for epoch in range(num_epochs):
    model.train()
    total_loss, correct, total = 0, 0, 0

    for images, labels in train_loader:
        images, labels = images.to(device), labels.to(device)
        optimizer.zero_grad()
        outputs = model(images)
        loss = criterion(outputs, labels)
        loss.backward()
        optimizer.step()

        total_loss += loss.item()
        _, predicted = outputs.max(1)
        correct += (predicted == labels).sum().item()
        total += labels.size(0)

    acc = correct / total
    print(f" Epoch {epoch+1}/{num_epochs} - Loss: {total_loss:.4f} - Train Acc: {acc:.4f}")

# === Save new model ===
torch.save(model.state_dict(), model_save_path)
print(f"\n Model saved to: {model_save_path}")

# === Evaluation on shared test set ===
model.eval()
all_preds, all_labels = [], []

with torch.no_grad():
    for images, labels in test_loader:
        images = images.to(device)
        outputs = model(images)
        preds = outputs.argmax(dim=1).cpu().numpy()
        all_preds.extend(preds)
        all_labels.extend(labels.numpy())

# === Metrics & Confusion Matrix ===
print("\n Classification Report (Test Set):")
print(classification_report(all_labels, all_preds, target_names=class_names))

cm = confusion_matrix(all_labels, all_preds)
plt.figure(figsize=(6, 5))
sns.heatmap(cm, annot=True, fmt="d", cmap="Blues",
            xticklabels=class_names, yticklabels=class_names)
plt.xlabel("Predicted")
plt.ylabel("True")
plt.title("ConvNeXt Confusion Matrix (Fixed Test Set)")
plt.tight_layout()
plt.show()
